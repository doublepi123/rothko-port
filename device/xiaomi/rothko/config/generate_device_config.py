#!/usr/bin/env python3
"""Generate the make fragments from config/device-parameters.json.

The JSON file is the canonical, evidence-backed description. The two generated
make fragments are checked in so that a source checkout can be built without a
Python JSON parser in the build path, while --check keeps them honest.

Usage:
    config/generate_device_config.py             # write fragments
    config/generate_device_config.py --check     # fail if fragments are stale
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HEADER = """\
# Generated by config/generate_device_config.py from config/device-parameters.json.
# Do not edit by hand. Evidence for every value is recorded in the JSON file and
# in docs/EVIDENCE.md. Regenerate with:
#     python3 config/generate_device_config.py
"""


def _bool(value: object) -> str:
    if not isinstance(value, bool):
        raise ValueError(f"expected bool, got {value!r}")
    return "true" if value else "false"


def validate_app_mode(arch: dict) -> None:
    if arch.get("supports_32_bit_apps") is not False or arch.get("supports_64_bit_apps") is not True:
        raise ValueError("rothko device-specific vendor/ODM evidence requires 64-bit apps only")
    if arch.get("zygote") != "zygote64":
        raise ValueError("app ABI and effective ODM zygote must agree on zygote64")
    if arch.get("retain_native_32_bit_variants") and arch.get("second_arch") != "arm":
        raise ValueError("native ARM32 variants must not be silently removed with 32-bit apps")


def render_board(cfg: dict) -> str:
    device = cfg["device"]
    arch = cfg["architecture"]
    validate_app_mode(arch)
    parts = cfg["partitions"]
    sup = cfg["super"]

    lines = [HEADER]
    lines.append(f"ROTHKO_DEVICE_CODENAME := {device['codename']}")
    lines.append(f"ROTHKO_MODEL := {device['model']}")
    lines.append(f"ROTHKO_MARKET_NAME := {device['market_name']}")
    lines.append(f"ROTHKO_PLATFORM := {device['platform']}")
    lines.append(f"ROTHKO_FIRMWARE := {device['firmware_incremental']}")
    lines.append(f"ROTHKO_VENDOR_SDK := {device['vendor_sdk']}")
    lines.append(f"ROTHKO_VENDOR_API_LEVEL := {device.get('vendor_api_level', device['vendor_sdk'])}")
    lines.append(f"ROTHKO_FRAMEWORK_TARGET_LEVEL := {device.get('framework_target_level', 8)}")
    lines.append(f"ROTHKO_SEPOLICY_VERSION := {device.get('sepolicy_version', '34.0')}")
    lines.append(f"ROTHKO_VNDK_VERSION := {device.get('vndk_version', '34')}")
    lines.append("")

    lines.append("# Architecture")
    lines.append(f"TARGET_ARCH := {arch['arch']}")
    lines.append(f"TARGET_ARCH_VARIANT := {arch['arch_variant']}")
    lines.append(f"TARGET_CPU_ABI := {arch['cpu_abi']}")
    lines.append(f"TARGET_CPU_ABI2 := {arch['cpu_abi2']}")
    lines.append(f"TARGET_CPU_VARIANT := {arch['cpu_variant']}")
    lines.append(f"TARGET_CPU_VARIANT_RUNTIME := {arch['cpu_variant_runtime']}")
    lines.append("# Native secondary architecture is independent of app ABI advertising.")
    lines.append(f"TARGET_2ND_ARCH := {arch['second_arch']}")
    lines.append(f"TARGET_2ND_ARCH_VARIANT := {arch['second_arch_variant']}")
    lines.append(f"TARGET_2ND_CPU_ABI := {arch['second_cpu_abi']}")
    lines.append(f"TARGET_2ND_CPU_ABI2 := {arch['second_cpu_abi2']}")
    lines.append(f"TARGET_2ND_CPU_VARIANT := {arch['second_cpu_variant']}")
    lines.append(f"TARGET_2ND_CPU_VARIANT_RUNTIME := {arch['second_cpu_variant_runtime']}")
    lines.append(f"TARGET_USES_64_BIT_BINDER := {_bool(arch['uses_64_bit_binder'])}")
    lines.append("")

    lines.append("# Platform and bootloader identity")
    lines.append(f"TARGET_BOARD_PLATFORM := {device['platform']}")
    lines.append(f"TARGET_BOOTLOADER_BOARD_NAME := {device['codename']}")
    lines.append("")

    lines.append("# Fixed image partitions (bytes)")
    for name in ("boot", "init_boot", "vendor_boot", "dtbo"):
        size = parts[name]["fixed_partition_size"]
        var = {
            "boot": "BOARD_BOOTIMAGE_PARTITION_SIZE",
            "init_boot": "BOARD_INIT_BOOT_IMAGE_PARTITION_SIZE",
            "vendor_boot": "BOARD_VENDOR_BOOTIMAGE_PARTITION_SIZE",
            "dtbo": "BOARD_DTBOIMG_PARTITION_SIZE",
        }[name]
        lines.append(f"{var} := {size}")
    lines.append("")

    lines.append("# Dynamic partitions: OTA metadata target layout, not live super metadata")
    lines.append(f"BOARD_SUPER_PARTITION_SIZE := {sup['live_size']}")
    lines.append(f"BOARD_SUPER_PARTITION_GROUPS := {sup['ota_group']['name']}")
    target_partitions = sup.get("build_target_partitions", sup["ota_group"]["partitions"])
    lines.append(
        "BOARD_MAIN_PARTITION_LIST := "
        + " ".join(target_partitions)
    )
    lines.append(f"BOARD_MAIN_SIZE := {sup['ota_group']['size']}")
    lines.append("")

    lines.append("# Stock prebuilt images and BOARD_PREBUILT_* flags are owned by")
    lines.append("# vendor/xiaomi/rothko/BoardConfigVendor.mk, which BoardConfig.mk includes.")
    if parts["init_boot"]["use"] != "prebuilt_stock":
        raise ValueError("init_boot must be prebuilt_stock in phase 1 (stock generic ramdisk)")
    lines.append("# init_boot, boot, vendor_boot, dtbo, vendor, odm and dlkm partitions are")
    lines.append("# stock prebuilts. system, system_ext and product are built by Lineage.")
    lines.append("# mi_ext is inspection_pending: not staged, target not mounted, phone")
    lines.append("# partition preserved; no prebuilt/build hook is assumed.")
    lines.append("")
    return "\n".join(lines)


def validate_ota_partition_plan(plan: dict) -> list[str]:
    if plan["avb"]["enabled"] is not False:
        raise ValueError("this offline tree requires AVB signing to remain disabled")
    produced = [*plan["built_by_lineage"], *plan["stock_prebuilt"]]
    parts = plan["ota_partitions"]
    if not isinstance(parts, list) or any(not isinstance(part, str) for part in parts):
        raise ValueError("OTA partitions must be a list of image names")
    if len(produced) != len(set(produced)) or len(parts) != len(set(parts)):
        raise ValueError("duplicate partition in the image or OTA plan")
    expected = set(produced)
    if set(parts) != expected:
        raise ValueError(
            "OTA partitions must match the built or staged image plan: "
            f"missing={sorted(expected - set(parts))}, "
            f"unavailable={sorted(set(parts) - expected)}"
        )
    return parts


def render_product(cfg: dict) -> str:
    device = cfg["device"]
    arch = cfg["architecture"]
    validate_app_mode(arch)
    vab = cfg["virtual_ab"]
    plan = cfg["build_plan"]
    parts = validate_ota_partition_plan(plan)

    lines = [HEADER]
    lines.append("# Match the device-specific ODM zygote; do not use the generic mgvi template.")
    lines.append(f"TARGET_SUPPORTS_32_BIT_APPS := {_bool(arch['supports_32_bit_apps'])}")
    lines.append(f"TARGET_SUPPORTS_64_BIT_APPS := {_bool(arch['supports_64_bit_apps'])}")
    lines.append("# PRODUCT_VENDOR_PROPERTIES cannot alter the retained vendor prebuilt.")
    lines.append(f"PRODUCT_PRODUCT_PROPERTIES += ro.zygote={arch['zygote']}")
    lines.append("PRODUCT_PRODUCT_PROPERTIES += dalvik.vm.dex2oat64.enabled=true")
    lines.append("")
    lines.append(f"PRODUCT_SHIPPING_API_LEVEL := {plan['shipping_api_level']}")
    lines.append("PRODUCT_USE_DYNAMIC_PARTITIONS := true")
    lines.append("PRODUCT_BUILD_SUPER_PARTITION := true")
    lines.append("PRODUCT_BUILD_VENDOR_BOOT_IMAGE := false")
    lines.append(f"PRODUCT_BUILD_VBMETA_IMAGE := {_bool(plan['avb']['enabled'])}")
    lines.append("")
    lines.append("# Virtual A/B values from the OTA payload metadata")
    lines.append(f"PRODUCT_VIRTUAL_AB_COW_VERSION := {vab['cow_version']}")
    lines.append(f"PRODUCT_VIRTUAL_AB_COMPRESSION_METHOD := {vab['compression']}")
    lines.append(f"PRODUCT_VIRTUAL_AB_COMPRESSION_FACTOR := {vab['compression_factor']}")
    lines.append(f"PRODUCT_VIRTUAL_AB_OTA := {_bool(vab['vabc_enabled'])}")
    lines.append("")
    lines.append("AB_OTA_UPDATER := true")
    lines.append("# List only images built or staged by this offline configuration.")
    lines.append("AB_OTA_PARTITIONS += \\")
    for index, part in enumerate(parts):
        suffix = " \\" if index != len(parts) - 1 else ""
        lines.append(f"    {part}{suffix}")
    lines.append("")
    lines.append("# AVB signing is disabled: the OEM private keys are unavailable.")
    lines.append("# Generated images are unsigned and are not flashable.")
    lines.append(f"# shipping API {plan['shipping_api_level']} follows vendor API {device.get('vendor_api_level', device['vendor_sdk'])};")
    lines.append("# the boot image is Android 16 but the vendor/odm stack is Android 14/SDK 34, FCM target-level 8.")
    lines.append("# Do not set vendor API 36.")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    default_root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--device-root", default=str(default_root))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    device_root = Path(args.device_root).resolve()
    config_dir = device_root / "config"
    if config_dir.is_symlink() or device_root not in config_dir.resolve().parents:
        print(f"refusing to write outside the device root: {config_dir}", file=sys.stderr)
        return 2
    config_path = config_dir / "device-parameters.json"
    with config_path.open("r", encoding="utf-8") as handle:
        cfg = json.load(handle)
    vendor_api = cfg.get("device", {}).get("vendor_api_level", cfg.get("device", {}).get("vendor_sdk"))
    shipping_api = cfg.get("build_plan", {}).get("shipping_api_level")
    if vendor_api != 34 or shipping_api != 34:
        raise ValueError(
            "this tree requires vendor API 34 and shipping API 34; "
            f"got vendor_api_level={vendor_api!r}, shipping_api_level={shipping_api!r}. "
            "Do not set vendor API 36 for the Android 16 boot image with an Android 14/SDK 34 vendor stack."
        )

    outputs = {
        device_root / "config" / "device-parameters.mk": render_board(cfg),
        device_root / "config" / "product-parameters.mk": render_product(cfg),
    }

    stale = []
    for path, content in outputs.items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if args.check:
            if old != content:
                stale.append(path)
                print(f"stale: {path}", file=sys.stderr)
        else:
            path.write_text(content, encoding="utf-8")

    if args.check and stale:
        print("run: python3 config/generate_device_config.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
